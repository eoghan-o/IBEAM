function [xq, wq] = mapTriQuad(qp, qw, v)

    % gp is (ngauss x 2): [r s]
    r = qp(:,1);
    s = qp(:,2);

    lambda1 = 1 - r - s;
    lambda2 = r;
    lambda3 = s;

    % Map points
    xq = lambda1.*v(1,:) + lambda2.*v(2,:) + lambda3.*v(3,:);

    % Jacobian
    J = [v(2,:) - v(1,:); v(3,:) - v(1,:)]';
    detJ = abs(det(J));

    % Weights
    wq = qw * detJ;
end