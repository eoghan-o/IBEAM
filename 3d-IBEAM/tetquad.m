function [xq, wq] = mapTetQuad(qp, w, v)
    % qp is (ngauss x 3): [r s t]
    % qw is (ngauss x 1): weights on reference tet
    % v  is (4 x 3):      [x1 y1 z1; x2 y2 z2; x3 y3 z3; x4 y4 z4]
    r = qp(:,1);
    s = qp(:,2);
    t = qp(:,3);
    lambda1 = 1 - r - s - t;
    lambda2 = r;
    lambda3 = s;
    lambda4 = t;

    % Map points
    xq = lambda1.*v(1,:) + lambda2.*v(2,:) + lambda3.*v(3,:) + lambda4.*v(4,:);

    % Jacobian (3x3): columns are edge vectors from v1
    J = [v(2,:) - v(1,:); ...
         v(3,:) - v(1,:); ...
         v(4,:) - v(1,:)]';
    detJ = abs(det(J));

    % Weights
    wq = w * detJ;
end